      final band1 = Band();
      final artifact1 = Artifact(20, 20);
      artifact1.setBothLocation(const IntOffset(20, 10));
      band1.addArtifact(artifact1);

      final band2 = Band();
      final artifact2 = Artifact(20, 20);
      artifact2.setBothLocation(const IntOffset(10, 10));
